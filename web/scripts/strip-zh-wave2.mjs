// Remove dangerous empty or single-char targets
const safe = FRAGMENTS.filter(([from, to]) => from.length >= 2 && to.length >= 1);
safe.sort((a, b) => b[0].length - a[0].length);

function walk(dir, acc = []) {
  for (const name of fs.readdirSync(dir)) {
    const p = path.join(dir, name);
    const st = fs.statSync(p);
    if (st.isDirectory()) walk(p, acc);
    else if (/\.(tsx|ts)$/.test(name) && !name.includes(".test.")) acc.push(p);
  }
  return acc;
}

let changed = 0;
for (const file of walk(ROOT)) {
  let text = fs.readFileSync(file, "utf8");
  const orig = text;
  for (const [from, to] of safe) {
    if (text.includes(from)) text = text.split(from).join(to);
  }
  if (text !== orig) {
    fs.writeFileSync(file, text);
    changed++;
  }
}
console.log(`wave2: updated ${changed} files, ${safe.length} rules`);
