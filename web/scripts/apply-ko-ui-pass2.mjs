function walk(dir, files = []) {
  for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, f.name);
    if (f.isDirectory()) walk(p, files);
    else if (/\.(tsx?|mjs)$/.test(f.name)) files.push(p);
  }
  return files;
}

let n = 0;
for (const file of walk(SRC)) {
  let s = fs.readFileSync(file, "utf8");
  if (!/[\u4e00-\u9fff]/.test(s) && !s.includes("꺼짐自动") && !s.includes("已켜짐")) continue;
  const orig = s;
  for (const [a, b] of R) if (s.includes(a)) s = s.replaceAll(a, b);
  if (s !== orig) {
    fs.writeFileSync(file, s);
    n++;
    console.log(path.relative(SRC, file));
  }
}
